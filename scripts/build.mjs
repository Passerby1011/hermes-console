#!/usr/bin/env node
/**
 * hermes-console · 构建链（唯一产物生成者，禁止手改产物）。
 *
 *   node plugins/hermes-console/scripts/build.mjs
 *
 * 输入 → 输出：
 *   src/main.js  ──esbuild bundle(esm, external react/sdk)──▶ dashboard/dist/index.js
 *   src/style.css ──esbuild bundle(+@import tokens.css)──────▶ dashboard/dist/style.css
 *   dashboard/dist/index.js ──逐字节镜像──▶ desktop/plugin.js（Electron 半，同源同字节）
 *
 * 为什么不是 `import esbuild from 'esbuild'`：本脚本位于插件目录，node 的裸模块解析
 * 从脚本所在目录向上找 node_modules，而本机唯一的 esbuild 在 `hermes-agent/node_modules`。
 * 直接 spawn esbuild 自带的 CLI 入口（`node .../esbuild/bin/esbuild`）可以避开这条解析链，
 * 且不会因 npx/网络失败而静默退出。
 *
 * 幂等性：esbuild 的输出不含时间戳，同一输入两次构建字节相同（验收时会跑两遍比对 sha256）。
 * 颜色纪律：构建前扫描源码与产物，出现 `#rrggbb` / `rgb()` / `hsl()` / 字面 black|white 立即失败。
 *
 * 用法：
 *   node scripts/build.mjs           一次性构建（默认；产物稳定可 diff）
 *   node scripts/build.mjs --watch   监听 src/ 持续构建（开发时用，产物同样不含时间戳）
 */
import { spawn, spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, readFileSync, mkdirSync, readdirSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..') // plugins/hermes-console
const SRC = join(ROOT, 'src')
const DIST = join(ROOT, 'dashboard', 'dist')
const DESKTOP = join(ROOT, 'desktop')

const BANNER_JS =
  '/*! hermes-console — GENERATED by scripts/build.mjs from src/main.js. DO NOT EDIT BY HAND. */'
const BANNER_CSS =
  '/*! hermes-console — GENERATED by scripts/build.mjs from src/style.css. DO NOT EDIT BY HAND. */'

/** esbuild CLI 入口候选（按顺序取第一个存在的）。 */
function findEsbuild() {
  const candidates = [
    process.env.HERMES_ESBUILD || '',
    resolve(ROOT, '../../hermes-agent/node_modules/esbuild/bin/esbuild'),
    resolve(ROOT, '../../node_modules/esbuild/bin/esbuild'),
    resolve(ROOT, 'node_modules/esbuild/bin/esbuild')
  ].filter(Boolean)
  for (const candidate of candidates) {
    if (existsSync(candidate)) return candidate
  }
  throw new Error(
    'esbuild 未找到。已尝试：\n  ' +
      candidates.join('\n  ') +
      '\n可用 HERMES_ESBUILD=<path/to/esbuild/bin/esbuild> 显式指定。'
  )
}

const ESBUILD = findEsbuild()

function runEsbuild(args, what) {
  const result = spawnSync(process.execPath, [ESBUILD, ...args], {
    cwd: ROOT,
    encoding: 'utf8'
  })
  if (result.error) throw new Error(`${what}: 无法启动 esbuild — ${result.error.message}`)
  if (result.status !== 0) {
    throw new Error(
      `${what}: esbuild 退出码 ${result.status}\n--- stdout ---\n${result.stdout || ''}\n--- stderr ---\n${result.stderr || ''}`
    )
  }
}

function sha256(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex')
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else out.push(full)
  }
  return out
}

// 只在颜色位置上禁止字面色值；`transparent` / `currentColor` / `inherit` 是合法关键字。
const FORBIDDEN = [
  { re: /#[0-9a-fA-F]{3,8}\b/g, what: '十六进制颜色' },
  { re: /\brgba?\s*\(/g, what: 'rgb()/rgba()' },
  { re: /\bhsla?\s*\(/g, what: 'hsl()/hsla()' },
  { re: /:\s*(?:black|white)\b/g, what: '字面 black/white' }
]

function assertNoHardcodedColors() {
  const files = [...walk(SRC), join(DIST, 'style.css'), join(DIST, 'index.js')].filter((f) =>
    /\.(css|js)$/.test(f)
  )
  const problems = []
  for (const file of files) {
    const text = readFileSync(file, 'utf8')
    for (const { re, what } of FORBIDDEN) {
      re.lastIndex = 0
      let m
      while ((m = re.exec(text)) !== null) {
        problems.push(`${file.replace(/\\/g, '/')}: ${what} ${JSON.stringify(m[0])}`)
      }
    }
  }
  if (problems.length) {
    throw new Error('颜色只能来自主题变量 var(--ui-*)，发现字面色值：\n  ' + problems.join('\n  '))
  }
}

// ---------------------------------------------------------------------------
const WATCH = process.argv.includes('--watch')

mkdirSync(DIST, { recursive: true })
mkdirSync(DESKTOP, { recursive: true })

// 样式必须以**字符串**进 JS bundle：桌面端插件运行时只加载门牌 plugin.js，
// 不读 manifest.json 的 `css` 键（4 个在桌面端显示正常的面板全是内联样式/无 css 键），
// 所以外链 style.css 在桌面侧永远不生效。`--loader:.css=text` 让 src/style.css 与
// src/tokens.css 作为字符串被 import，再由 src/lib/style-inject.js 插进 <head>。
// CSS_ARGS 那一路仍然生成 dist/style.css —— 它只服务 web dashboard SPA。
const JS_ARGS = [
  join(SRC, 'main.js'),
  '--bundle',
  '--format=esm',
  '--platform=browser',
  '--target=chrome110',
  '--jsx=automatic',
  '--loader:.css=text',
  '--external:react',
  '--external:react/jsx-runtime',
  '--external:@hermes/plugin-sdk',
  '--legal-comments=none',
  '--charset=utf8',
  `--banner:js=${BANNER_JS}`,
  `--outfile=${join(DIST, 'index.js')}`
]

const CSS_ARGS = [
  join(SRC, 'style.css'),
  '--bundle',
  '--charset=utf8',
  `--banner:css=${BANNER_CSS}`,
  `--outfile=${join(DIST, 'style.css')}`
]

if (WATCH) {
  // 开发模式：两个 esbuild 子进程各自 --watch，由它们负责写产物。
  // 一次性校验（字节数 / 颜色 / desktop 镜像）留给普通构建，所以这里直接交接。
  console.log('esbuild  :', ESBUILD)
  console.log('watch    : src/ →', DIST.replace(/\\/g, '/'))
  console.log('注意     : watch 不刷新 desktop/plugin.js；发布前跑一次不带 --watch 的构建。')
  const kids = [JS_ARGS, CSS_ARGS].map((args) =>
    spawn(process.execPath, [ESBUILD, ...args, '--watch=forever'], { cwd: ROOT, stdio: 'inherit' })
  )
  process.on('SIGINT', () => {
    for (const kid of kids) kid.kill()
    process.exit(0)
  })
} else {
  runEsbuild(JS_ARGS, 'build js')
  runEsbuild(CSS_ARGS, 'build css')
}

const jsOut = join(DIST, 'index.js')
const cssOut = join(DIST, 'style.css')
if (!WATCH) {
  for (const [file, min] of [
    [jsOut, 512],
    [cssOut, 512]
  ]) {
    if (!existsSync(file)) throw new Error(`产物缺失: ${file}`)
    const size = statSync(file).size
    if (size < min) throw new Error(`产物过小（${size} B < ${min} B）: ${file}`)
  }

  assertNoHardcodedColors()

  // 样式必须真的在 bundle 里自注入：少任何一条都说明「面板会裸奔」这个缺陷又回来了。
  const jsText = readFileSync(jsOut, 'utf8')
  for (const marker of ['data-hermes-console-style', '.hc-card {', '.hc-cards {']) {
    if (jsText.indexOf(marker) === -1) {
      throw new Error('产物缺少 ' + marker + ' —— 样式字符串没有进 bundle（--loader:.css=text 掉了？）')
    }
  }

  // desktop/plugin.js = dist/index.js 的逐字节镜像（同源，不是另一份手写实现）
  const doorOut = join(DESKTOP, 'plugin.js')
  copyFileSync(jsOut, doorOut)
  if (sha256(jsOut) !== sha256(doorOut)) throw new Error('desktop/plugin.js 与 dist/index.js 字节不一致')

  const rows = [
    ['dashboard/dist/index.js', jsOut],
    ['dashboard/dist/style.css', cssOut],
    ['desktop/plugin.js', doorOut]
  ].map(([label, file]) => ({ label, size: statSync(file).size, sha: sha256(file) }))

  const pad = (s, n) => String(s).padEnd(n)
  console.log('esbuild  :', ESBUILD)
  console.log('outdir   :', DIST.replace(/\\/g, '/'))
  for (const row of rows) {
    console.log(`  ${pad(row.label, 26)} ${String(row.size).padStart(6)} B  sha256=${row.sha}`)
  }
  console.log('BUILD-OK')
}
